CREATE TABLE jobs (
    log_hash varchar,
    jobid BIGINT,
    uid_hash VARCHAR,
    job_name VARCHAR,
    start DATETIME,
    end DATETIME,
    runtime TIME,
    nthreads INTEGER,
    nprocs INTEGER,
    lib_ver VARCHAR,
    cb_nodes INTEGER,
    exe varchar,
    log_hash, job_id PRIMARY KEY
)

-- The table containing all files. Each file can have multiple logs associated with
-- it (we may reuse input files in different jobs, for example). 
-- 
CREATE TABLE files (
    log_hash VARCHAR,
    id UBIGINT,
    path VARCHAR,
    mount VARCHAR,
)

-- POSIX values can be set to -1 if the value was unable to be collected. So, we're
-- forced to use BIGINT. The posix table contains all of the information contained 
